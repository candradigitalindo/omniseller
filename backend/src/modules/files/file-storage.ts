import { createReadStream } from "node:fs";
import { copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";
import {
  DeleteObjectCommand,
  GetObjectCommand,
  ListObjectsV2Command,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import type { EnvFor } from "../../config/env.schema";

export const FILE_STORAGE = Symbol("FILE_STORAGE");

/**
 * Where private files live (technology doc 13): Cloudflare R2 in staging and production, MinIO or a
 * local directory in development. Keys are generated by FilesService (`t/<tenant>/<purpose>/<id>.<ext>`),
 * never taken from a request.
 */
export interface FileStorage {
  readonly bucket: string;
  put(key: string, bytes: Uint8Array, mime: string): Promise<void>;
  /** Uploads a file from disk without reading it into memory (the full data export). */
  putFile(key: string, path: string, mime: string): Promise<void>;
  get(key: string): Promise<Uint8Array>;
  delete(key: string): Promise<void>;
  /** Every object under a prefix (`t/<tenant>/`: a closed business's purge, backend doc 8.36); how many went. */
  deletePrefix(prefix: string): Promise<number>;
  /** A short-lived link the browser downloads from directly; null where the api serves the file itself. */
  signedUrl(key: string, opts: SignedUrlOptions): Promise<string | null>;
}

export interface SignedUrlOptions {
  filename: string;
  mime: string;
  ttlSeconds: number;
  /** `inline` opens PDFs in the browser; `attachment` saves the file (ZIP). Default inline. */
  disposition?: "inline" | "attachment";
}

/** Files in a directory (local and test only): the api reads them back for downloads. */
export class LocalFileStorage implements FileStorage {
  readonly bucket = "local";
  private readonly root: string;

  constructor(dir: string) {
    this.root = resolve(dir);
  }

  private path(key: string): string {
    const p = resolve(this.root, key);
    if (!p.startsWith(this.root + sep)) throw new Error("file key outside the storage directory");
    return p;
  }

  async put(key: string, bytes: Uint8Array, _mime?: string): Promise<void> {
    const p = this.path(key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, bytes);
  }

  async putFile(key: string, path: string, _mime?: string): Promise<void> {
    const p = this.path(key);
    await mkdir(dirname(p), { recursive: true });
    await copyFile(path, p);
  }

  async get(key: string): Promise<Uint8Array> {
    return new Uint8Array(await readFile(this.path(key)));
  }

  async delete(key: string): Promise<void> {
    await rm(this.path(key), { force: true });
  }

  async deletePrefix(prefix: string): Promise<number> {
    const dir = this.path(prefix.replace(/\/+$/, ""));
    const files = await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => []);
    await rm(dir, { recursive: true, force: true });
    return files.filter((f) => f.isFile()).length;
  }

  async signedUrl(): Promise<null> {
    return null;
  }
}

/** Cloudflare R2 (or MinIO) through the S3 API; downloads are presigned GET links. */
export class R2FileStorage implements FileStorage {
  private readonly s3: S3Client;

  constructor(
    readonly bucket: string,
    config: { endpoint: string; accessKeyId: string; secretAccessKey: string },
  ) {
    this.s3 = new S3Client({
      region: "auto",
      endpoint: config.endpoint,
      credentials: { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey },
      // R2 and MinIO both serve path-style requests; MinIO serves nothing else
      forcePathStyle: true,
      // Checksums only where S3 requires them: the SDK default (CRC32 in an aws-chunked trailer) is not
      // what R2 documents, and a streamed upload (putFile) must reach storage as the file's exact bytes
      requestChecksumCalculation: "WHEN_REQUIRED",
      responseChecksumValidation: "WHEN_REQUIRED",
    });
  }

  async put(key: string, bytes: Uint8Array, mime: string): Promise<void> {
    await this.s3.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: bytes, ContentType: mime }));
  }

  async putFile(key: string, path: string, mime: string): Promise<void> {
    const { size } = await stat(path);
    await this.s3.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Body: createReadStream(path),
        ContentLength: size,
        ContentType: mime,
      }),
    );
  }

  async get(key: string): Promise<Uint8Array> {
    const out = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    if (!out.Body) throw new Error(`empty object ${key}`);
    return out.Body.transformToByteArray();
  }

  async delete(key: string): Promise<void> {
    await this.s3.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }

  // one object at a time: DeleteObjects needs a checksum header R2 does not document (see the client above)
  async deletePrefix(prefix: string): Promise<number> {
    let deleted = 0;
    let token: string | undefined;
    do {
      const page = await this.s3.send(
        new ListObjectsV2Command({ Bucket: this.bucket, Prefix: prefix, ContinuationToken: token }),
      );
      for (const o of page.Contents ?? []) {
        if (!o.Key) continue;
        await this.delete(o.Key);
        deleted++;
      }
      token = page.IsTruncated ? page.NextContinuationToken : undefined;
    } while (token);
    return deleted;
  }

  signedUrl(key: string, opts: SignedUrlOptions): Promise<string> {
    return getSignedUrl(
      this.s3,
      new GetObjectCommand({
        Bucket: this.bucket,
        Key: key,
        ResponseContentType: opts.mime,
        ResponseContentDisposition: `${opts.disposition ?? "inline"}; filename="${opts.filename}"`,
      }),
      { expiresIn: opts.ttlSeconds },
    );
  }
}

export function fileStorageFor(env: EnvFor<"api"> | EnvFor<"worker">): FileStorage {
  if (env.FILE_STORAGE === "local") return new LocalFileStorage(env.FILE_STORAGE_LOCAL_DIR);
  return new R2FileStorage(env.R2_BUCKET_DOCUMENTS, {
    endpoint: env.R2_ENDPOINT ?? `https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
    accessKeyId: env.R2_ACCESS_KEY_ID!,
    secretAccessKey: env.R2_SECRET_ACCESS_KEY!,
  });
}
