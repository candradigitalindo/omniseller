import type { StockMovementType } from "@omniseller/shared";
import { sql } from "drizzle-orm";
import { boolean, integer, jsonb, pgTable, text } from "drizzle-orm/pg-core";
import { appendOnlyColumns, baseColumns, qty, tstz, ulid } from "../columns";

export const warehouse = pgTable("warehouse", {
  ...baseColumns(),
  code: text("code").notNull(),
  name: text("name").notNull(),
  address: jsonb("address").$type<Record<string, unknown>>().notNull(),
  isDefault: boolean("is_default").notNull().default(false),
  active: boolean("active").notNull().default(true),
  deletedAt: tstz("deleted_at"),
});

/** Quantities change only via InventoryService.applyMovement -> apply_stock_movement() (invariant I2). */
export const inventory = pgTable("inventory", {
  ...baseColumns(),
  variantId: ulid("variant_id").notNull(),
  warehouseId: ulid("warehouse_id").notNull(),
  onHand: qty("on_hand").notNull().default(0),
  reserved: qty("reserved").notNull().default(0),
  buffer: qty("buffer").notNull().default(0),
  damaged: qty("damaged").notNull().default(0),
  /** on_hand - reserved - buffer; negative means oversold. Generated by PostgreSQL. */
  available: qty("available").generatedAlwaysAs(sql`on_hand - reserved - buffer`),
  binLocation: text("bin_location"),
  minStock: qty("min_stock"),
});

export type StockReferenceType =
  | "order_item"
  | "return_item"
  | "stock_count_line"
  | "stock_transfer_line"
  | "goods_receipt_line"
  | "campaign_stock_hold"
  | "migration_job"
  | "manual";

/** Ledger; append only, written by apply_stock_movement(). */
export const stockMovement = pgTable("stock_movement", {
  ...appendOnlyColumns(),
  variantId: ulid("variant_id").notNull(),
  warehouseId: ulid("warehouse_id").notNull(),
  type: text("type").$type<StockMovementType>().notNull(),
  onHandDelta: qty("on_hand_delta").notNull().default(0),
  reservedDelta: qty("reserved_delta").notNull().default(0),
  damagedDelta: qty("damaged_delta").notNull().default(0),
  bufferDelta: qty("buffer_delta").notNull().default(0),
  onHandAfter: qty("on_hand_after").notNull(),
  reservedAfter: qty("reserved_after").notNull(),
  damagedAfter: qty("damaged_after").notNull(),
  bufferAfter: qty("buffer_after").notNull(),
  referenceType: text("reference_type").$type<StockReferenceType>(),
  referenceId: ulid("reference_id"),
  reason: text("reason"),
  note: text("note"),
  actorUserId: ulid("actor_user_id"),
});

export const stockAllocationRule = pgTable("stock_allocation_rule", {
  ...baseColumns(),
  storeId: ulid("store_id").notNull(),
  channelWarehouseId: ulid("channel_warehouse_id"),
  variantId: ulid("variant_id"),
  mode: text("mode").$type<"all" | "percent" | "fixed">().notNull(),
  value: qty("value").notNull().default(0),
  buffer: qty("buffer").notNull().default(0),
  priority: integer("priority").notNull().default(100),
  active: boolean("active").notNull().default(true),
});
